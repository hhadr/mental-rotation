#!/usr/bin/env node
// Generates js/stimuli.js from js/config.js. Rerun after changing any stimulus setting:
//   node tools/build-stimuli.mjs
import { writeFileSync } from 'node:fs';
import { CONFIG } from '../js/config.js';
import { buildStimuli } from '../js/design.js';

const stimuli = buildStimuli(CONFIG);
const target = new URL('../js/stimuli.js', import.meta.url);
writeFileSync(target, `// GENERATED by tools/build-stimuli.mjs - do not edit.\nexport const STIMULI = ${JSON.stringify(stimuli)};\n`);

const vis = [...stimuli.train, ...stimuli.test].map((t) => t.min_cube_visible);
console.log(`hash ${stimuli.hash}: ${stimuli.shapes.length} shapes, ${vis.length} trials`);
console.log(`worst-cube visibility: min ${Math.min(...vis)}, max ${Math.max(...vis)}`);
